# -*- coding: utf-8 -*-
"""
Corrections confirmed by reading the original page images.

Every entry here was checked against a rendered crop of the page it came from, at a
resolution where one hanzi is unambiguous. That matters because the earlier candidate
list was generated by string similarity and could not tell a typo from a different
compound - it offered "3-甲基-2-丁醇 -> 3-甲基-2-己醇" as readily as the right answer.

Two of the names turned out NOT to be errors at all, and they are recorded as such
rather than silently fixed:

    2-丁酮          the paper prints exactly this (RI 893, table 3.12 of #27)
    庚酸-3-甲基丁酯   the paper prints exactly this (RI 1562, table 3.8 of #27)

Where the page settles it by a neighbouring value rather than by reading the glyph, the
evidence is noted in the comment: retention index for the alcohols, odour threshold for
the esters. That is the difference between "these two characters look alike" and "the
value in the next column leaves only one reading possible".

Usage:
    python src/apply_confirmed_fixes.py [--dry-run]
"""

import argparse
import json
import os
import re
import sys

sys.stdout.reconfigure(encoding="utf-8")

HERE = os.path.dirname(os.path.abspath(__file__))
REOUT = os.path.abspath(os.path.join(HERE, "..", "out", "re整理"))

CONFIRMED = {
    # --- table 3-13 of #32, settled by the odour-threshold column -------------
    "』酸乙酯": ("丁酸乙酯",
                "表3-13 该行阈值 20 ug/L，表内另有乙酸乙酯 7500；首位被吞且非乙"),
    "乙酸已酯": ("乙酸己酯",
                 "表3-13 阈值 1500，表内另有乙酸丁酯 1600；乙酸己酯为独立一行"),
    "已酸异戊酯": ("己酸异戊酯",
                   "表3-13 阈值 1000，与乙酸己酯 1500 同族；己被认成已"),
    "2-羟基丙酸乙酯": ("2-羟基已酸乙酯",
                       "表3-13 该行阈值为空，与下一行 2-羟基己酸乙酯 并列"),
    "2-羟基已酸乙酯": ("2-羟基己酸乙酯",
                       "表3-13 已印作 2-羟基己酸乙酯；已与己混淆"),
    "2-甲基「酸乙酯": ("2-甲基丁酸乙酯",
                       "表3-13 同表另有 2-甲基丙酸乙酯(15)，「 处为丁"),
    # --- table 3-10 of #32, settled by the retention-index column -------------
    "1-」醇": ("1-丁醇",
              "表3-10 RI 1176，介于 1-戊醇 1263 与 1-己醇 1361 之间，符合正构序列"),
    "2-了醇": ("2-丁醇",
              "表3-10 RI 1109 为该表首行醇类；了为丁的断字"),
    # --- verified as printed in the source, NOT errors -------------------------
    "2-丁酮": None,           # #27 表3.12 原图即印作 2-丁酮 (RI 893)
    "庚酸-3-甲基丁酯": None,   # #27 表3.8 原图即印作 庚酸-3-甲基丁酯 (RI 1562)
}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--dry-run", action="store_true")
    a = ap.parse_args()

    hits = {k: 0 for k in CONFIRMED}
    cells = 0
    touched = 0

    for fn in sorted(f for f in os.listdir(REOUT)
                     if re.match(r"^(bm|en)_\d+\.json$", f)):
        p = os.path.join(REOUT, fn)
        d = json.load(open(p, encoding="utf-8"))
        changed = False
        for t in d.get("tables", []):
            for key in ("rows", "header_rows"):
                for row in t.get(key, []):
                    for j, cell in enumerate(row):
                        k = (cell or "").strip()
                        if k not in CONFIRMED:
                            continue
                        hits[k] += 1
                        repl = CONFIRMED[k]
                        if repl and cell != repl[0]:
                            row[j] = repl[0]
                            changed = True
                            cells += 1
        if changed:
            touched += 1
            if not a.dry_run:
                json.dump(d, open(p, "w", encoding="utf-8"),
                          ensure_ascii=False, indent=1)

    print("confirmed against page images:\n")
    for k, v in CONFIRMED.items():
        if v is None:
            print("   %-20s  KEEP   原图即如此，不是错误（%d 处）" % (k, hits[k]))
        else:
            print("   %-20s -> %-18s x%d" % (k, v[0], hits[k]))
            print("   %-20s    %s" % ("", v[1]))
    print()
    print("cells rewritten: %d   files touched: %d" % (cells, touched))
    if a.dry_run:
        print("\n(dry run)")


if __name__ == "__main__":
    main()
